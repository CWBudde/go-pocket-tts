// ensureVoiceDownloaded fetches a voice once; signal aborts the download
// (a model switch aborts the previous config's downloads).
async function ensureVoiceDownloaded(config, voiceID, signal) {
  if (!voiceID) return null;

  const key = voiceKey(config, voiceID);

  if (state.voiceBytes.has(key)) {
    return state.voiceBytes.get(key);
  }

  if (state.voiceDownloads.has(key)) {
    return state.voiceDownloads.get(key);
  }

  const voice = findVoice(config, voiceID);
  if (!voice) {
    const msg = `voice ${voiceID} is not a ${config} voice`;
    state.voiceErrors.set(key, msg);
    throw new Error(msg);
  }

  state.voiceErrors.delete(key);

  let lastPct = -1;
  const promise = (async () => {
    const bytes = await fetchBytesWithProgress(voice.url, (received, total) => {
      const pct = total > 0 ? Math.min(100, Math.round((received / total) * 100)) : 0;
      if (pct !== lastPct && pct % 10 === 0 && selectedVoiceKey() === key) {
        lastPct = pct;
        setAction(`Downloading voice ${voiceID} (${pct}%)...`);
      }
    }, signal);
    state.voiceBytes.set(key, bytes);
    return bytes;
  })();

  state.voiceDownloads.set(key, promise);
  renderInfo();
  setSynthesizeEnabled();

  try {
    const bytes = await promise;
    return bytes;
  } catch (err) {
    // An aborted download is retried the next time the voice is needed.
    if (err?.name !== "AbortError") state.voiceErrors.set(key, formatError(err));
    throw err;
  } finally {
    state.voiceDownloads.delete(key);
    renderInfo();
    setSynthesizeEnabled();
  }
}

async function downloadSelectedVoiceIfNeeded() {
  const config = state.config;
  const voiceID = selectedVoiceID();
  if (!voiceID) {
    renderInfo();
    setSynthesizeEnabled();
    return null;
  }

  const key = voiceKey(config, voiceID);
  if (state.voiceBytes.has(key)) {
    renderInfo();
    setSynthesizeEnabled();
    return state.voiceBytes.get(key);
  }

  setAction(`Downloading voice ${voiceID}...`);
  try {
    const bytes = await ensureVoiceDownloaded(config, voiceID, state.loadAbort?.signal);
    if (selectedVoiceKey() === key) {
      setAction(`Voice ${voiceID} ready.`);
    }
    return bytes;
  } catch (err) {
    if (err?.name !== "AbortError" && selectedVoiceKey() === key) {
      setAction(`Voice ${voiceID} failed: ${formatError(err)}`);
    }
    return null;
  }
}

// selectLanguage switches the page to config: it drops the previous model,
// downloads the new one and its tokenizer.json from Hugging Face and loads
// them into the kernel. A local checkpoint file (the gated kyutai/pocket-tts
// weights, which can clone voices) replaces the model download; the tokenizer
// still comes from the config. A later switch supersedes an earlier one, whose
// downloads are aborted and whose result is ignored.
async function selectLanguage(config, checkpointFile = null) {
  const lang = (state.catalog?.languages || []).find((l) => l.name === config);
  if (!lang) {
    setAction(`Unknown model config ${config}`);
    return;
  }

  state.loadSeq += 1;
  const seq = state.loadSeq;
  const isCurrent = () => seq === state.loadSeq;

  if (state.loadAbort) state.loadAbort.abort();
  const abort = new AbortController();
  state.loadAbort = abort;

  state.config = config;
  languageSelect.value = config;
  state.modelPhase = "downloading";
  state.modelError = "";
  state.checkpointName = checkpointFile ? checkpointFile.name : "";
  state.canClone = false;
  dropClonedVoices();
  resetRecording();
  applyLanguageDefaults(lang);
  renderInfo();
  setSynthesizeEnabled();

  void downloadSelectedVoiceIfNeeded();

  // Free the previous model before the new one arrives, also one a superseded
  // switch is still loading (the unload queues behind it).
  state.loadedConfig = "";
  void state.kernelReadyPromise
    .then(() => enqueueKernel(() => globalThis.PocketTTSKernel.unloadModel()))
    .catch(() => {});

  try {
    let modelPromise;
    if (checkpointFile) {
      showProgress(`Reading ${checkpointFile.name}...`, 0, false);
      setAction(`Reading local checkpoint ${checkpointFile.name} for ${config}...`);
      modelPromise = checkpointFile.arrayBuffer().then((buf) => new Uint8Array(buf));
    } else {
      showProgress(`Downloading ${config}...`, 0, false);
      setAction(`Downloading ${config} model...`);
      modelPromise = fetchBytesWithProgress(
        lang.model,
        (received, total) => {
          if (!isCurrent()) return;
          const pct = total > 0 ? Math.min(100, Math.round((received / total) * 100)) : 0;
          showProgress(`Downloading ${config}... ${pct}%`, pct, false);
          setAction(`Downloading ${config} model (${pct}%)...`);
        },
        abort.signal,
      );
    }

    const [modelBytes, tokenizerBytes] = await Promise.all([
      modelPromise,
      fetchBytesWithProgress(lang.tokenizer, null, abort.signal),
    ]);

    await state.kernelReadyPromise;

    const result = await enqueueKernel(async () => {
      if (!isCurrent()) return null;

      state.modelPhase = "initializing";
      showProgress(`Initializing ${config}...`, 0, false);
      setAction(`Initializing ${config}...`);

      return globalThis.PocketTTSKernel.loadModel(
        modelBytes,
        tokenizerBytes,
        (evt) => {
          if (!isCurrent()) return;
          const stage = evt?.stage || "load";
          const pct = Math.round(Math.max(0, Math.min(100, Number(evt?.percent || 0))));
          showProgress(`Initializing ${config} (${stage})... ${pct}%`, pct, false);
          setAction(`Initializing ${config} (${stage} ${pct}%)...`);
        },
        { config },
      );
    });

    if (!isCurrent()) return;
    if (!result?.ok) {
      throw new Error(result?.error || "model load failed");
    }

    state.loadedConfig = result.config || config;
    state.modelPhase = "ready";
    state.canClone = !!result.can_clone;
    showProgress(`${config} ready`, 100, true);
    setAction(`${config} ready (${modelSourceText()}).`);
    setTimeout(hideProgress, 2000);
  } catch (err) {
    // A stopped kernel has already said so; its calls fail with noise.
    if (!isCurrent() || state.kernelStopped) return;
    state.modelPhase = "error";
    state.modelError = formatError(err);
    hideProgress();
    setAction(`${config} failed: ${state.modelError}`);
  } finally {
    if (isCurrent()) {
      renderInfo();
      setSynthesizeEnabled();
    }
  }
}

// cloneVoiceFromWAV encodes a WAV prompt with the loaded checkpoint's voice
// encoder and adds the result as clone-<baseName> to the voice dropdown of the
// config it was cloned for, cached like a downloaded voice. wavBytes may also
// be a promise of the bytes (a file still being read). sourceLabel names the
// prompt in status messages. It reports whether the voice was cloned.
async function cloneVoiceFromWAV(wavBytes, sourceLabel, baseName) {
  const config = state.config;
  // A checkpoint switch while the clone runs drops cloned voices; the result
  // of this one would come from the previous checkpoint's encoder.
  const loadSeq = state.loadSeq;
  if (!modelReady() || !state.canClone) {
    renderInfo();
    return false;
  }

  const voiceID = `clone-${baseName}`;

  state.isCloning = true;
  setSynthesizeEnabled();
  setAction(`Cloning voice from ${sourceLabel}...`);

  try {
    const promptBytes = await wavBytes;
    const result = await enqueueKernel(() => {
      if (state.loadSeq !== loadSeq || state.loadedConfig !== config) {
        throw new Error(`the ${config} checkpoint is no longer loaded`);
      }
      return globalThis.PocketTTSKernel.cloneVoice(promptBytes);
    });
    if (!result?.ok) {
      throw new Error(result?.error || "voice cloning failed");
    }
    if (state.loadSeq !== loadSeq) {
      throw new Error("the checkpoint changed while cloning; clone the voice again");
    }

    state.voiceBytes.set(voiceKey(config, voiceID), result.voice_safetensors);
    state.voiceErrors.delete(voiceKey(config, voiceID));
    const ids = clonedVoiceIDs(config).filter((id) => id !== voiceID);
    state.clonedVoices.set(config, [...ids, voiceID]);

    if (state.config === config) {
      const lang = state.catalog.languages.find((l) => l.name === config);
      populateVoiceDropdown(lang);
      voiceSelect.value = voiceID;
    }
    setAction(`Cloned voice ${voiceID} from ${sourceLabel} (${result.frames} frames).`);
    return true;
  } catch (err) {
    setAction(`Voice cloning failed: ${formatError(err)}`);
    return false;
  } finally {
    state.isCloning = false;
    renderInfo();
    setSynthesizeEnabled();
  }
}

function cloneVoiceFromFile(file) {
  const base = file.name.replace(/\.[^.]*$/, "").trim() || "voice";
  // cloneVoiceFromWAV awaits the read, so a failed read fails the clone; the
  // empty catch only keeps a rejection its guards skip from going unhandled.
  const wavBytes = file.arrayBuffer().then((buf) => new Uint8Array(buf));
  wavBytes.catch(() => {});
  return cloneVoiceFromWAV(wavBytes, file.name, base);
}

// resetRecording closes the microphone panel: it stops a running capture,
// drops the last take and supersedes a pending start or stop.
function resetRecording() {
  state.recordSeq += 1;
  if (state.recorder) {
    state.recorder.cancel();
    state.recorder = null;
  }
  if (state.recording) {
    URL.revokeObjectURL(state.recording.url);
    state.recording = null;
  }
  state.recordPhase = "closed";
}

function openRecordPanel() {
  if (state.recordPhase === "closed") {
    state.recordPhase = "ready";
    recordScript.textContent = readingScript(state.config);
    setRecordMeter(0, 0);
  }
  renderRecordPanel();
  recordPanel.scrollIntoView({ behavior: "smooth", block: "nearest" });
}

// startTake asks for the microphone and starts a recording. The panel can
// close and the model can switch while the browser asks for permission; a
// recorder that arrives after that is cancelled.
async function startTake() {
  if (state.recordPhase !== "ready" || !modelReady() || !state.canClone) return;
  const seq = state.recordSeq + 1;
  state.recordSeq = seq;
  const isCurrent = () => seq === state.recordSeq;

  state.recordPhase = "starting";
  setRecordMeter(0, 0);
  setAction("Waiting for microphone permission...");
  setSynthesizeEnabled();

  let recorder;
  try {
    recorder = await startRecording({
      maxSeconds: recordMaxSeconds,
      onProgress: ({ seconds, level }) => {
        if (isCurrent()) setRecordMeter(seconds, level);
      },
      onLimit: () => {
        if (isCurrent()) void stopTake();
      },
    });
  } catch (err) {
    if (!isCurrent()) return;
    state.recordPhase = "ready";
    setAction(`Recording failed: ${formatError(err)}`);
    setSynthesizeEnabled();
    return;
  }

  if (!isCurrent()) {
    recorder.cancel();
    return;
  }
  state.recorder = recorder;
  state.recordPhase = "recording";
  setAction(`Recording at ${recorder.sampleRate} Hz...`);
  setSynthesizeEnabled();
}

async function stopTake() {
  const recorder = state.recorder;
  if (state.recordPhase !== "recording" || !recorder) return;
  const seq = state.recordSeq;
  const isCurrent = () => seq === state.recordSeq;

  state.recordPhase = "stopping";
  setSynthesizeEnabled();

  try {
    const { wav, seconds } = await recorder.stop();
    if (!isCurrent()) return;
    state.recorder = null;
    if (seconds <= 0) {
      throw new Error("no audio was captured");
    }

    const url = URL.createObjectURL(new Blob([wav], { type: "audio/wav" }));
    state.recording = { wav, url, seconds };
    state.recordPhase = "recorded";
    if (seconds < recordShortSeconds) {
      setAction(`Short recording (${seconds.toFixed(1)} s); 10 s or more clone better.`);
    } else {
      setAction(`Recorded ${seconds.toFixed(1)} s.`);
    }
  } catch (err) {
    if (!isCurrent()) return;
    state.recorder = null;
    state.recordPhase = "ready";
    setAction(`Recording failed: ${formatError(err)}`);
  } finally {
    if (isCurrent()) setSynthesizeEnabled();
  }
}

function retakeRecording() {
  if (state.recordPhase !== "recorded") return;
  if (state.recording) {
    URL.revokeObjectURL(state.recording.url);
    state.recording = null;
  }
  state.recordPhase = "ready";
  void startTake();
}

function discardRecording() {
  const discarded = state.recordPhase !== "ready" && state.recordPhase !== "closed";
  resetRecording();
  if (discarded) {
    setAction("Recording discarded.");
  }
  setSynthesizeEnabled();
}

// cloneRecording clones the last take. A failed clone keeps it for a retry.
async function cloneRecording() {
  const recording = state.recording;
  if (state.recordPhase !== "recorded" || !recording || state.isCloning) return;

  const n = state.recordingCount + 1;
  const ok = await cloneVoiceFromWAV(recording.wav, "your recording", `recording-${n}`);
  if (!ok) return;

  state.recordingCount = n;
  if (state.recording === recording) {
    resetRecording();
    setSynthesizeEnabled();
  }
}

function rAF() {
  return new Promise((resolve) => requestAnimationFrame(resolve));
}

async function runSynthesis(text) {
  try {
    const options = { temperature: parseFloat(temperatureSlider.value) };
    const voiceSafetensors = await downloadSelectedVoiceIfNeeded();
    if (voiceSafetensors) {
      options.voiceSafetensors = voiceSafetensors;
    }

    const t0 = performance.now();
    const result = await globalThis.PocketTTSKernel.synthesize(
      text,
      (evt) => {
        const pct = Math.round(Math.max(0, Math.min(100, Number(evt?.percent || 0))));
        const stage = evt?.stage || "working";
        const detail = evt?.detail || stage;
        showProgress(`Synthesizing... ${pct}%`, pct, false);
        setAction(`Synthesizing — ${detail} (${pct}%)`);
      },
      options,
    );
    const elapsedMs = (performance.now() - t0).toFixed(1);

    if (!result?.ok) {
      throw new Error(result?.error || "synthesis failed");
    }

    const wavBytes = decodeBase64ToBytes(result.wav_base64 || "");
    setAudioBlob(wavBytes);
    showProgress(`Done in ${elapsedMs} ms`, 100, true);
    setAction(`Synthesis complete in ${elapsedMs} ms.`);
    setTimeout(hideProgress, 3000);
  } catch (err) {
    hideProgress();
    setAction(`Synthesis failed: ${formatError(err)}`);
  } finally {
    state.isSynthesizing = false;
    renderInfo();
    setSynthesizeEnabled();
  }
}

function handleSynthesize() {
  if (synthBtn.disabled || state.isSynthesizing) {
    return;
  }

  state.isSynthesizing = true;
  state.textDirty = false;
  setSynthesizeEnabled();
  showProgress("Synthesizing...", 0, false);
  setAction("Synthesizing...");

  // Capture text now; user may freely edit while synthesis runs.
  const text = textArea.value;

  // Yield to the browser so the UI repaints before the heavy WASM call.
  rAF().then(() => runSynthesis(text));
}

async function loadCatalog() {
  const res = await fetch(catalogAssetPath);
  if (!res.ok) {
    throw new Error(`fetch ${catalogAssetPath} failed (${res.status})`);
  }

  const catalog = await res.json();
  if (!catalog?.languages?.length) {
    throw new Error(`${catalogAssetPath} lists no model configs`);
  }

  state.catalog = catalog;
  populateLanguageDropdown();
}

async function initApp() {
  renderInfo();
  setSynthesizeEnabled();

  // Boot the kernel while the model downloads.
  state.kernelReadyPromise = bootKernel();
  state.kernelReadyPromise.catch((err) => {
    setAction(`Kernel startup failed: ${formatError(err)}`);
    setSynthesizeEnabled();
  });

  try {
    await loadCatalog();
  } catch (err) {
    setAction(`Model list unavailable: ${formatError(err)}`);
    return;
  }

  await selectLanguage(state.catalog.default || state.catalog.languages[0].name);
}

