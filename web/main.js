// renderRecordPanel shows the controls of the current recording step. Starting
// a take and cloning one need the same model state as cloning from a file.
function renderRecordPanel() {
  const phase = state.recordPhase;
  const recorded = phase === "recorded" && !!state.recording;
  const idle = modelReady() && state.canClone && !state.isCloning && !state.isSynthesizing;

  recordPanel.hidden = phase === "closed";
  recordPanel.classList.toggle("live", phase === "recording");
  recordMeter.hidden = recorded;

  recordStartBtn.hidden = phase !== "ready" && phase !== "starting";
  recordStartBtn.disabled = phase === "starting" || !idle;
  recordStopBtn.hidden = !isRecording();
  recordStopBtn.disabled = phase === "stopping";
  recordStopBtn.classList.toggle("live", phase === "recording");
  recordCloneBtn.hidden = !recorded;
  recordCloneBtn.disabled = !idle;
  recordRetakeBtn.hidden = !recorded;
  recordRetakeBtn.disabled = !idle;
  recordDiscardBtn.textContent = phase === "ready" ? "Close" : "Discard";
  recordDiscardBtn.disabled = phase === "stopping";

  // Only touch the media source when it changes: reassigning it would reset
  // the player.
  const url = recorded ? state.recording.url : "";
  if ((recordPreview.getAttribute("src") || "") !== url) {
    recordPreview.pause();
    if (url) {
      recordPreview.src = url;
    } else {
      recordPreview.removeAttribute("src");
      recordPreview.load();
    }
  }
  recordPreview.hidden = !recorded;
  if (url) {
    recordDownload.href = url;
  } else {
    recordDownload.removeAttribute("href");
  }
  recordDownload.hidden = !recorded;
}

async function fetchBytesWithProgress(url, onProgress, signal) {
  const res = await fetch(url, { signal });
  if (!res.ok) {
    throw new Error(`fetch ${url} failed (${res.status})`);
  }

  const contentLength = parseInt(res.headers.get("content-length") || "0", 10);
  if (!res.body) {
    const buf = await res.arrayBuffer();
    if (onProgress) onProgress(buf.byteLength, buf.byteLength);
    return new Uint8Array(buf);
  }

  const reader = res.body.getReader();
  const chunks = [];
  let received = 0;

  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    chunks.push(value);
    received += value.length;
    if (onProgress) onProgress(received, contentLength);
  }

  const out = new Uint8Array(received);
  let offset = 0;
  for (const chunk of chunks) {
    out.set(chunk, offset);
    offset += chunk.length;
  }
  if (onProgress) onProgress(received, contentLength || received);
  return out;
}

async function bootKernel() {
  const go = new Go();
  const wasm = await WebAssembly.instantiateStreaming(fetch(kernelAssetPath), go.importObject);
  // The kernel never returns on its own; it exits on a fatal error such as
  // running out of WASM memory, after which every call fails.
  go.run(wasm.instance).then(() => {
    state.kernelReady = false;
    state.kernelStopped = true;
    state.modelPhase = "error";
    state.modelError = "kernel stopped";
    hideProgress();
    setAction("The WASM kernel stopped (likely out of memory); reload the page.");
    setSynthesizeEnabled();
  });

  const kernel = globalThis.PocketTTSKernel;
  if (!kernel) {
    throw new Error("PocketTTSKernel not found after wasm startup");
  }
  for (const fn of ["synthesize", "loadModel", "unloadModel", "cloneVoice"]) {
    if (typeof kernel[fn] !== "function") {
      throw new Error(`PocketTTSKernel.${fn} is missing`);
    }
  }

  state.kernelReady = true;
  state.kernelVersion = String(kernel.version || "unknown");
  renderInfo();
  setSynthesizeEnabled();
}

// enqueueKernel runs task after every kernel task queued before it.
function enqueueKernel(task) {
  const run = state.kernelChain.then(task);
  state.kernelChain = run.catch(() => {});
  return run;
}

